def solve_expressions(A: int, B: int, C: int) -> tuple[int, int, int]:
    """
    Вычисляет значения трех логических выражений с помощью битовых операций.

    Параметры:
    A, B, C -- целые числа (для моделирования логики удобно использовать 0 и 1).

    Возвращает:
    Кортеж из трех целых чисел (результаты expr1, expr2, expr3).
    """
    # Маска для отсечения лишних битов (оставляем только 3 бита для переменных A, B, C)
    MASK = 0b111

    # Выражение 1: ¬(A ∧ B) ∨ ¬(A ∨ C)
    # Упрощенная форма: ¬A ∨ ¬B
    # В битовых операциях ~X эквивалентно ¬X, но для чистоты 3-битной логики
    # можно использовать X ^ MASK. Однако стандартный ~ тоже даст верный результат
    # после применения маски в конце.
    expr1 = (~(A & B) | ~(A | C)) & MASK

    # Выражение 2: (A ∧ B) ∨ (¬B ∧ C)
    expr2 = ((A & B) | ((~B) & C)) & MASK

    # Выражение 3: (A ∧ B) ∨ ¬C
    expr3 = ((A & B) | (~C)) & MASK

    return expr1, expr2, expr3


# Протестируем на всех возможных комбинациях 0 и 1 (таблица истинности)
print("A | B | C |  Ex1 | Ex2 | Ex3 | Ex1_simp")
print("-----------------------------------------")

for A in [0, 1]:
    for B in [0, 1]:
        for C in [0, 1]:
            e1, e2, e3 = solve_expressions(A, B, C)

            # Проверка упрощенной формы первого выражения: ¬A ∨ ¬B
            e1_simple = (~A | ~B) & 0b111

            print(f"{A} | {B} | {C} |  {e1}    |  {e2}    |  {e3}    |   {e1_simple}")

